KEYFRAME_DESCRIPTION_WRITING_GUIDE = """\
## 关键帧画面描述

每条 `keyframes[].description` 都会直接作为单张关键帧图片的画面描述，必须把当前静态画面的视觉信息写完整。
保持当前 unit 正式正文中的人物、场景、动作与物件事实不变；可以补足实现这些事实所需的摄影构图、空间关系、姿态、光线与焦点，
但不得增加新的故事事件、人物、物件或动作结果。

每条描述按以下顺序组织；当前画面中存在的项目都要交代清楚：

- **镜头与透视**：说明画幅方向、景别、机位高度、俯仰角度、拍摄方向和透视关系，以及主体采用全身、半身还是局部入画。
- **构图与空间层次**：说明每个主体位于画面的左、中、右及前景、中景、后景，主体所占画面比例、视觉主次、留白、
  框景或引导线关系；多主体画面要逐一写清彼此的距离、朝向和前后关系。
- **主体状态**：逐一说明每个可见角色的身体朝向、站姿或坐姿、头部方向、视线、表情、双臂、双手与手指的位置，
  以及动作刚开始时与其他角色或物体的接触关系。递交、拿取、触碰等互动要写清哪只手、接触点、手掌朝向和物体所在位置。
- **尺度、地面与遮挡**：说明人物、场景结构、家具和道具之间的真实相对尺度、相对高度、地面关系及合理遮挡；
  保证脸、双手、关键动作和关键道具清楚可见。需要锁定尺度时，用人物身体部位等可见参照表达，不使用含糊的“大、近、远”。
- **场景与物体**：说明与当前画面有关的场景结构、前后景元素，以及关键物体的位置、方向、轮廓和可见面；
  只写支持当前画面的环境信息，不罗列无关陈设。
- **光线与焦点**：说明主光方向、明暗关系、必要的轮廓光或投影，以及画面焦点和景深层次；关键人物的脸、双手和互动道具要清晰可辨。
- **物理合理性与定向避免**：先用正向描述锁定真实空间关系，再根据当前构图补充这张图最可能出现的错误。
  人物、肢体、服装、道具、家具、墙面和门框之间不得穿插、粘连或融合；人物脚底自然接触地面，主体不得悬空，
  前后景遮挡与远近尺度必须符合位置关系。除非当前 unit 正式正文明确要求，不得让人物站在家具或道具上、身体穿过物体，
  或让人物与物体无故巨大化、缩小成玩具。避免项必须针对当前场景，不堆叠与画面无关的通用负面词。

描述当前这一帧实际可见的状态，不叙述运镜过程、连续动作或后续结果。动作刚开始时，要把人物和物体各自所在的位置、
朝向、姿态与接触状态写清，不能提前画出摔倒后、碰撞后或动作完成后的结果。实际可见的人物、场景、道具与产品使用
`@[名称]` 引用，名称只能来自候选表；不可见或尚未出现的资产不要写入描述。
"""


